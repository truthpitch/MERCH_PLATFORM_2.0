## What do we mean by truth?

Truth is simply what is real, whether we like it or not. A fact doesn''t change because we disagree with it, ignore it or find it inconvenient. The sun doesn''t rise because we believe in it. It rises.

That doesn''t mean we always *know* the truth. We often see only part of it. But there is a difference between saying "I haven''t found the full truth yet" and saying "there is no truth at all". The first keeps us searching. The second makes us stop.

## Why awareness of truth matters

- **It protects you.** If you know truth exists, you start asking questions. That makes you harder to mislead by spin, propaganda or clever marketing.
- **It frees you.** Living in line with what is real is lighter than defending a story you know is not quite right.
- **It connects people.** Real conversations need a shared starting point. Truth is that common ground, even when we disagree about what to do with it.
- **It builds trust.** People and brands that tell the truth, also when it costs them something, are the ones we come back to.

> Truth doesn''t need to be loud. It needs to be noticed.

## Truth versus opinion

An opinion says *"I think"*. A fact says *"this is"*. Both have their place, but mixing them up causes a lot of confusion.

A simple test: could it be checked? "This shirt is made of organic cotton" can be checked. "This is the best shirt in the world" is an opinion. Learning to see the difference is the first step in becoming more aware.

## What hides the truth?

Truth rarely disappears. It gets covered up, often without bad intentions.

- **Noise:** so much information that the important things drown.
- **Echo chambers:** only hearing people who already agree with us.
- **Wishful thinking:** believing what we *want* to be true.
- **Spin:** facts that are technically correct, but told in a way that misleads.
- **Fear:** keeping quiet because the truth might be unpopular.

## Six habits to stay aware of truth

1. **Ask "how do we know this?"** before sharing or believing something.
2. **Go to the source.** Read the original, not only the headline or the summary.
3. **Listen to the other side.** Not to win, but to understand what they see that you might not.
4. **Separate facts from feelings.** Both are real, but they answer different questions.
5. **Be willing to be wrong.** Changing your mind when the evidence changes is a strength, not a weakness.
6. **Say it plainly.** Clear words leave less room for confusion. Honesty doesn''t need decoration.

## Truth takes courage

Knowing the truth is one thing. Standing for it is another. Sometimes it means saying the uncomfortable thing at the dinner table, admitting a mistake at work, or simply not going along with something you know isn''t right.

That kind of courage is rarely dramatic. It''s found in small, everyday choices: being honest with others, and first of all with yourself.

